import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer } from '../src/server.js';
import { parseCourse } from '../src/content.js';
import { UserError } from '../src/config.js';

// This demo never constructs a live Moodle adapter or loads .env. Only this
// invented course is available, and no URL is fetched or authorized by the fixture.
export async function buildDemo() {
  const course = parseCourse(await readFile(new URL('../test/fixtures/demo-course.html', import.meta.url), 'utf8'), 42, 'https://courses.example');
  course.coverage = { partial: true, pagesVisited: 1,
    warnings: [{ code: 'SECTION_UNAVAILABLE', url: 'https://courses.example/course/section.php?id=99' }] };
  const adapter = {
    run: operation => Promise.resolve().then(operation),
    getCourse: async id => {
      if (id !== 42) throw new UserError('Only the invented demo course is available.');
      return structuredClone(course);
    },
  };
  const server = createServer(adapter);
  const client = new Client({ name: 'synthetic-demo', version: '1.0.0' });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  try {
    await server.connect(serverTransport);
    await client.connect(clientTransport);
    const args = { courseId: 42, query: 'лабораториски', limit: 5 };
    const response = await client.callTool({ name: 'search_course', arguments: args });
    if (response.isError) throw new Error('Demo tool call failed.');
    const result = JSON.parse(response.content[0].text);
    if (result.matches.length !== 1 || !result.coverage.partial ||
      new URL(result.matches[0].url).hostname !== 'courses.example') throw new Error('Unexpected demo fixture.');
    return `# Synthetic MCP demo

All course names, content and IDs below are invented. URLs use the reserved
\`.example\` domain, not a faculty site. No credentials, browser, .env, faculty
connection or model API key is used.

## Student

> Во избраниот предмет „Измислени информациски системи“ најди ги лабораториските упатства. Наведи извор и кажи ако нешто не е проверено.

## MCP call

Tool: \`search_course\`

~~~json
${JSON.stringify(args, null, 2)}
~~~

## MCP result

The complete JSON below is generated by the production tool registration,
validation, result encoder and course-page search over an invented HTML fixture.
The course reader is synthetic and deliberately reports one unavailable section;
this is not live faculty compatibility evidence.

~~~json
${JSON.stringify(result, null, 2)}
~~~

## Assistant explanation

> Најдов „${result.matches[0].name}“ во секцијата „${result.matches[0].section}“.
>
> Извор: [Лабораториски упатства](${result.matches[0].url}).
>
> Покриеноста е нецелосна: една секција не беше достапна. Ова не е потврда дека нема други материјали. Пребарувањето ги провери видливите наслови/описи, а не содржината на поврзаниот документ.

English equivalent: “I found the lab guide in the visible course-page metadata,
with a source link. One section was unavailable, so I cannot confirm this is the
complete set of materials. The linked document itself was not read.”

The explanation is authored sample wording, not an AI/model evaluation or a promise
that every client will phrase its answer this way. An empty search under the same
partial coverage would also remain inconclusive.

## Reproduce without faculty access

With the project's locked npm dependencies installed, run \`npm run demo\`.
No Chromium installation or local credentials are required. \`npm run demo:check\`
regenerates the transcript in memory and checks this document for drift.
For an intentional update, run \`node scripts/demo.js > docs/DEMO.md\` and review it.
The normal runtime entry point does not import this demo fixture/adapter.

See the [student quickstart](STUDENT_QUICKSTART.md),
[tool contracts](MCP-CONTRACTS.md) and [safe reporting guide](REPORTING_LAYOUTS.md).
`;
  } finally {
    await client.close();
    await server.close();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  (async () => {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Unknown demo option.');
    const text = await buildDemo();
    if (process.argv.includes('--check')) {
      const saved = await readFile(new URL('../docs/DEMO.md', import.meta.url), 'utf8');
      if (saved.replace(/\r\n/g, '\n') !== text) throw new Error('Demo documentation drift.');
      console.log('Synthetic MCP demo matches the generated transcript.');
    } else process.stdout.write(text);
  })().catch(() => {
    console.error('Synthetic demo failed or documentation needs regeneration. No live credentials or content were read.');
    process.exitCode = 1;
  });
}
